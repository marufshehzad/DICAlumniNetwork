async function cleanup() {
  /* Phase 7E §31: a role-targeted notification has no user_id, so deleting the
     account that triggered it leaves it behind. These are removed by the text
     this run put in them. */
  try {
    await db.query(
      `DELETE FROM notifications
        WHERE target_role IS NOT NULL AND user_id IS NULL
          AND (title LIKE $1 OR subtitle LIKE $1)`, [`%${TAG}%`]);
  } catch {}
  try {
    await db.query(
      `DELETE FROM notifications WHERE link_entity='event' AND link_id IN
        (SELECT id FROM events WHERE title LIKE $1)`, [TAG + '%']);
  } catch {}
  for (const q of [
    ['DELETE FROM job_applications WHERE job_id IN (SELECT id FROM jobs WHERE title LIKE $1)', TAG + '%'],
    ['DELETE FROM jobs WHERE title LIKE $1', TAG + '%'],
    ['DELETE FROM events WHERE title LIKE $1', TAG + '%'],
    ['DELETE FROM stories WHERE title LIKE $1', TAG + '%'],
    ['DELETE FROM users WHERE email LIKE $1', TAG + '%'],
    ['DELETE FROM import_history WHERE filename LIKE $1', TAG + '%']
  ]) { try { await db.query(q[0], [q[1]]); } catch {} }
}

/* Route inventory, the same way security_smoke reads it, so the matrix below is
   generated from the source rather than from a list somebody maintains. */
function routesFromSource() {
  const FILES = ['server.js', 'routes_v2.js', 'routes_events.js', 'routes_reports.js',
                 'routes_admin_users.js', 'routes_compliance.js', 'routes_planner.js'];
  const out = [];
  for (const f of FILES) {
    if (!fs.existsSync(path.join(REPO, f))) continue;
    const src = fs.readFileSync(path.join(REPO, f), 'utf8').replace(/\r\n/g, '\n');
    src.split('\n').forEach((line, i) => {
      const m = /app\.(get|post|put|patch|delete)\(\s*(['"`])([^'"`]+)\2\s*,?\s*(.*)$/.exec(line);
      if (!m) return;
      const [, method, , route] = m;
      if (route.includes('${')) return;
      const rest = m[4] || '';
      let guard = 'public';
      const g = /requireRole\(([^)]*)\)/.exec(rest);
      if (g) guard = g[1].replace(/\.\.\./g, '').trim();
      else if (/requireScheduler/.test(rest)) guard = 'scheduler';
      else if (/requireVerified/.test(rest)) guard = 'verified';
      else if (/requireAuth/.test(rest)) guard = 'auth';
      out.push({ method: method.toUpperCase(), route, guard, where: `${f}:${i + 1}` });
    });
  }
  return out;
}

/* ============================================================
   DIC ALUMNI PLATFORM — Phase 7E full-system QA
   The final engineering quality gate.

   This suite covers the parts of Phase 7E that a machine can decide, and it
   deliberately does NOT re-implement what other suites already prove. Where
   coverage exists — the event workflow in acceptance/qa1/qa2, ticket signing in
   qa2, the audit chain in tamper — this suite verifies the boundary rather than
   the feature.

     A  authentication: every state, and no enumeration oracle
     B  the authorization matrix, generated by calling every route as every role
     C  department scope, attacked through every parameter a caller controls
     D  privacy: 7 fields × 3 levels × 6 viewers, with no staff bypass on location
     E  CSV under hostile content: commas, quotes, newlines, Bengali, formulas
     F  stored XSS: payloads planted, then read back through every reader
     G  error disclosure: nothing internal reaches a caller
     H  security headers, read off the wire
     I  donations: no client-settled money, no invented gateway
     J  notifications reach the right person and nobody else

   Writes SECURITY_AUTHORIZATION_MATRIX.md from what it observed, so the
   document cannot drift from the code again.

   Everything created is disposable and removed, including on the error path.

   Usage:  node tests/phase7e_full_qa.js
   ============================================================ */

